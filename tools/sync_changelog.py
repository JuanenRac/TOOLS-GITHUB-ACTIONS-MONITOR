"""One source of truth for the history: monitor/CHANGELOG.md. The CHANGELOG.md of the repository root is a generated copy (a short header and the whole history).

    python tools/sync_changelog.py            write the root file
    python tools/sync_changelog.py --check    fail when it differs (the CI runs it)
    python tools/sync_changelog.py --notes 1.6.2    print the section of one version (the text of its GitHub release)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "monitor" / "CHANGELOG.md"
TARGET = ROOT / "CHANGELOG.md"
HEADER = """<!--
  Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>
  GPL-3.0-or-later - see LICENSE
  Generated by tools/sync_changelog.py from monitor/CHANGELOG.md: edit that file, not this one.
-->

# Changelog

The history of GitHub Actions Monitor, from the first version to the latest. Each version groups its changes under Added, Changed, Fixed and Security.

"""


def history(text):
    """Everything from the first version heading on."""
    i = text.index("\n## [")
    block = text[i + 1:]
    return block.rstrip("\n") + "\n"


def section(text, version):
    m = re.search(r"^## \[%s\]\n(.*?)(?=^## \[|\Z)" % re.escape(version), text, re.S | re.M)
    return m.group(1).strip("\n") + "\n" if m else None


def versions(text):
    return re.findall(r"^## \[(\d[^\]]*)\]", text, re.M)


def generated():
    return HEADER + history(SOURCE.read_text(encoding="utf-8").replace("\r\n", "\n"))


def main(argv):
    if "--notes" in argv:
        found = section(SOURCE.read_text(encoding="utf-8").replace("\r\n", "\n"), argv[argv.index("--notes") + 1])
        if not found:
            print("NOTES=FAIL no such version")
            return 1
        sys.stdout.write(found)
        return 0
    want = generated()
    have = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.is_file() else ""
    if "--check" in argv:
        print("CHANGELOG=" + ("PASS the root file is the copy of monitor/CHANGELOG.md" if have == want else "FAIL CHANGELOG.md differs from monitor/CHANGELOG.md (run tools/sync_changelog.py)"))
        return 0 if have == want else 1
    TARGET.write_text(want, encoding="utf-8", newline="\n")
    print("CHANGELOG=WRITTEN %s" % TARGET)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
